"""Train the neural guard and write src/dust/data/guard-v0.npz.

    python training/generate.py && python training/train_guard.py

Deterministic for a given numpy version: fixed seeds, no threading-dependent ops.
A 10% development split of the synthetic data is held out to pick thresholds; the
hand-written evaluation set in data/eval/ is never seen here.
"""
from __future__ import annotations

import hashlib
import json
import sys
import time
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from dust.neural import LABELS, Guard, featurise, train_head  # noqa: E402

TRAIN = ROOT / "data" / "train.jsonl"
OUT = ROOT / "src" / "dust" / "data" / "guard-v0.npz"


def main() -> None:
    t0 = time.time()
    raw = TRAIN.read_bytes()
    rows = [json.loads(line) for line in raw.decode().splitlines()]
    rng = np.random.default_rng(381)
    order = rng.permutation(len(rows))
    n_dev = len(rows) // 10
    dev = [rows[i] for i in order[:n_dev]]
    train = [rows[i] for i in order[n_dev:]]

    X = [featurise(r["text"]) for r in train]
    y = np.array([LABELS.index(r["label"]) for r in train])
    W, b = train_head(X, y, len(LABELS), epochs=25, seed=1)

    groups = sorted({r["group"] for r in train if r["label"] == "contradicts"})
    gi = [i for i, r in enumerate(train) if r["label"] == "contradicts"]
    Wg, bg = train_head([X[i] for i in gi], np.array([groups.index(train[i]["group"]) for i in gi]),
                        len(groups), epochs=25, seed=2)

    guard = Guard(W, b, Wg, bg, groups, {})
    # dev metrics and thresholds
    p = np.array([guard.scores(r["text"])["contradicts"] for r in dev])
    gold = np.array([r["label"] == "contradicts" for r in dev])
    acc = float(np.mean([max(guard.scores(r["text"]).items(), key=lambda kv: kv[1])[0] == r["label"] for r in dev]))
    best = 0.5
    for t in np.linspace(0.5, 0.95, 46):
        pred = p >= t
        prec = (pred & gold).sum() / max(pred.sum(), 1)
        if prec >= 0.98:
            best = float(t)
            break
    meta = {
        "name": "dust-guard-v0",
        "licence": "Apache-2.0",
        "trained_on": "data/train.jsonl (synthetic, generated by training/generate.py)",
        "train_sha256": hashlib.sha256(raw).hexdigest(),
        "n_train": len(train), "n_dev": len(dev),
        "dev_accuracy": round(acc, 4),
        "threshold_block": round(best, 2),
        "threshold_flag": 0.35,
        "features": "hashed word 1-3 grams over entity-normalised text + char 3-5 grams, 2^18 buckets",
        "quantisation": "int8, per-class scale",
        "numpy": np.__version__,
    }
    guard.meta = meta
    guard.save(OUT)
    reloaded = Guard.load_file(OUT)
    drift = max(abs(reloaded.scores(r["text"])["contradicts"] - guard.scores(r["text"])["contradicts"]) for r in dev[:200])
    print(json.dumps({**meta, "max_quantisation_drift_on_dev": round(float(drift), 4),
                      "size_bytes": OUT.stat().st_size, "seconds": round(time.time() - t0, 1)}, indent=1))


if __name__ == "__main__":
    main()
