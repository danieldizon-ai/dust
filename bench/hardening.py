"""Robustness of the checker to evasion and to framing.

Takes every English benchmark item labelled `contradicts` that Dust blocks in its clean
form, applies deterministic perturbations, and reports how often it is still blocked,
with input hardening (``Layer(sanitize=True)``, the default) and without it.

Two framings are also tested in the other direction: the same sentence reported
("Arius taught that ...") or asked as a question should *pass*, because describing or
asking is not asserting.

This measures robustness, not accuracy: the base items are ones the checker already gets
right, drawn from both splits. Writes results/hardening.md and results/hardening.json.
`--check` fails if any count changes (CI).
"""
from __future__ import annotations

import argparse
import json
import random
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from dust import Layer  # noqa: E402

EVAL = ROOT / "data/eval/nicene-eval-v0.jsonl"
OUT_JSON = ROOT / "results/hardening.json"
OUT_MD = ROOT / "results/hardening.md"

CYR = {"a": "а", "e": "е", "o": "о", "p": "р", "c": "с", "x": "х", "y": "у", "i": "і"}


def _words(t):
    return t.split(" ")


def homoglyph(t, rng):
    ws = _words(t)
    idx = [i for i, w in enumerate(ws) if len(w) > 3 and any(ch in CYR for ch in w)]
    for i in rng.sample(idx, min(3, len(idx))):
        ws[i] = "".join(CYR.get(ch, ch) for ch in ws[i])
    return " ".join(ws)


def zero_width(t, rng):
    return " ".join(w[: len(w) // 2] + "​" + w[len(w) // 2:] if len(w) > 4 else w for w in _words(t))


def spaced(t, rng):
    ws = _words(t)
    cands = [i for i, w in enumerate(ws) if w.isalpha() and len(w) >= 5]
    if not cands:
        return t
    i = max(cands, key=lambda k: len(ws[k]))
    ws[i] = "-".join(ws[i])
    return " ".join(ws)


def fullwidth(t, rng):
    return "".join(chr(ord(c) + 0xFEE0) if "!" <= c <= "~" else c for c in t)


def friendly(t, rng):
    return "Honestly, just between us and with all respect to everyone: " + t


def _lower_first(t):
    return t[0].lower() + t[1:] if t and not t.startswith(("God", "Jesus", "Christ", "Mary", "I ")) else t


def reported(t, rng):
    return "Arius taught that " + _lower_first(t.rstrip("."))  + "."


def question(t, rng):
    return "Is it true that " + _lower_first(t.rstrip(".!")) + "?"


EVASIONS = [("homoglyphs (Cyrillic look-alikes)", homoglyph), ("zero-width characters", zero_width),
            ("letters spaced with hyphens", spaced), ("full-width characters", fullwidth),
            ("friendly framing", friendly)]
FRAMINGS = [("reported as a historical view", reported), ("asked as a question", question)]


def run() -> dict:
    items = [json.loads(line) for line in EVAL.read_text(encoding="utf-8").splitlines()]
    on, off = Layer(), Layer(sanitize=False)
    base = [it for it in items if it["lang"] == "en" and it["label"] == "contradicts"
            and "\n" not in it["text"] and on.check(it["text"]).decision == "block"]
    rng = random.Random(381)
    rows, examples = [], {}
    for name, fn in EVASIONS + FRAMINGS:
        want_block = (name, fn) in EVASIONS
        variants = [fn(it["text"], rng) for it in base]
        b_on = sum(on.check(v).decision == "block" for v in variants)
        b_off = sum(off.check(v).decision == "block" for v in variants)
        rows.append({"perturbation": name, "expected": "block" if want_block else "pass", "n": len(variants),
                     "blocked_with_hardening": b_on, "blocked_without": b_off})
        examples[name] = variants[0]
        if not want_block:
            single = [(it, v) for it, v in zip(base, variants) if not re.search(r"[;.!?]\s+\S", it["text"])]
            rows.append({"perturbation": name + ", single-clause items only", "expected": "pass", "n": len(single),
                         "blocked_with_hardening": sum(on.check(v).decision == "block" for _, v in single),
                         "blocked_without": sum(off.check(v).decision == "block" for _, v in single)})
    return {"base_items": len(base), "rows": rows, "examples": examples}


def to_md(r: dict) -> str:
    L = ["# Hardening: evasion and framing", "",
         f"Base: {r['base_items']} English items labelled `contradicts` that Dust blocks in clean form "
         "(both splits; this measures robustness, not accuracy). Generated by `bench/hardening.py`.", "",
         "| perturbation | should | n | still blocked, hardening on | still blocked, hardening off |",
         "|---|---|---|---|---|"]
    for row in r["rows"]:
        n = row["n"]
        L.append(f"| {row['perturbation']} | {row['expected']} | {n} | {row['blocked_with_hardening']} "
                 f"({row['blocked_with_hardening'] / n:.0%}) | {row['blocked_without']} ({row['blocked_without'] / n:.0%}) |")
    L += ["", "For the reported and question rows a *lower* number is better: describing or asking about a view "
          "should pass. In multi-clause items the attribution covers only the first clause, and the "
          "later, unattributed clauses (\"...; he never lived.\") are rightly read as the speaker's own "
          "assertion; the single-clause rows isolate the framing itself.", "", "## Examples (first item, as perturbed)", ""]
    for k, v in r["examples"].items():
        L.append(f"* {k}: `{v.encode('unicode_escape').decode('ascii') if any(ord(c) > 127 for c in v) else v}`")
    return "\n".join(L) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    r = run()
    if a.check:
        old = json.loads(OUT_JSON.read_text(encoding="utf-8"))
        if old["rows"] != r["rows"]:
            raise SystemExit("hardening results drifted")
        print("hardening results reproduce")
        return
    OUT_JSON.write_text(json.dumps(r, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    OUT_MD.write_text(to_md(r), encoding="utf-8")
    print(to_md(r))


if __name__ == "__main__":
    main()
