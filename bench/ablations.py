"""Ablation study: which parts of Dust matter, measured on the same benchmark.

    python bench/ablations.py      # writes results/ablations.md and results/ablations.json

Each variant changes one thing relative to the shipped configuration. Guard variants
are retrained in memory from data/train.jsonl with the same split and seed as
training/train_guard.py. Reported on the held-out test split and on all items.
"""
from __future__ import annotations

import copy
import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "bench"))

from dust.kb import load  # noqa: E402
from dust.layer import Layer  # noqa: E402
from dust.neural import LABELS, Guard, featurise, train_head  # noqa: E402
from run import EVAL, metrics, split  # noqa: E402


def train_guard(rows, flags: dict, frac: float = 1.0, seed: int = 381) -> Guard:
    rng = np.random.default_rng(seed)
    order = rng.permutation(len(rows))
    n_dev = len(rows) // 10
    train = [rows[i] for i in order[n_dev:]]
    if frac < 1.0:
        train = train[: int(len(train) * frac)]
    X = [featurise(r["text"], **flags) for r in train]
    y = np.array([LABELS.index(r["label"]) for r in train])
    W, b = train_head(X, y, len(LABELS), epochs=25, seed=1)
    groups = sorted({r["group"] for r in train if r["label"] == "contradicts"})
    gi = [i for i, r in enumerate(train) if r["label"] == "contradicts"]
    Wg, bg = train_head([X[i] for i in gi], np.array([groups.index(train[i]["group"]) for i in gi]), len(groups), epochs=25, seed=2)
    return Guard(W, b, Wg, bg, groups, {"feature_flags": flags, "threshold_block": 0.5, "threshold_flag": 0.35})


def evaluate(layer: Layer, items) -> dict:
    out = {}
    for name in ("test", "all"):
        sub = [it for it in items if name == "all" or split(it["id"]) == name]
        out[name] = metrics([(it["label"] == "contradicts", layer.check(it["text"]).decision == "block") for it in sub])
    return out


def main() -> None:
    items = [json.loads(line) for line in EVAL.read_text(encoding="utf-8").splitlines()]
    rows = [json.loads(line) for line in (ROOT / "data/train.jsonl").read_text(encoding="utf-8").splitlines()]
    shipped = Guard.load()
    no_rules = copy.deepcopy(load())
    no_rules.rules = []
    variants = [
        ("shipped: dual track", "Dust as released", Layer(guard=shipped)),
        ("no inference rules", "symbolic track matches literals directly against axioms; no chaining", Layer(kb=no_rules, guard=shipped)),
        ("no stance gate", "neural may block any sentence the symbolic track did not prove a contradiction in", Layer(guard=shipped, stance_gate=False)),
        ("no language restriction", "neural may block in any language", Layer(guard=shipped, restrict_languages=False)),
        ("symbolic only", "", Layer(mode="symbolic")),
        ("neural only", "", Layer(guard=shipped, mode="neural")),
    ]
    guard_variants = [
        ("guard: words only", {"words": True, "chars": False, "entities": True}, 1.0),
        ("guard: characters only", {"words": False, "chars": True, "entities": True}, 1.0),
        ("guard: no entity normalisation", {"words": True, "chars": True, "entities": False}, 1.0),
        ("guard: 25% of training data", {"words": True, "chars": True, "entities": True}, 0.25),
        ("guard: 50% of training data", {"words": True, "chars": True, "entities": True}, 0.5),
    ]
    for name, flags, frac in guard_variants:
        g = train_guard(rows, flags, frac)
        variants.append((name + " (dual)", f"retrained guard, features={flags}, fraction={frac}", Layer(guard=g)))
        variants.append((name + " (neural only)", "same guard without the symbolic track", Layer(guard=g, mode="neural")))
    results = []
    for name, desc, layer in variants:
        r = evaluate(layer, items)
        results.append({"variant": name, "description": desc, **r})
        print(f"{name:45s} test F1={r['test']['f1']:.3f} P={r['test']['precision']:.3f} R={r['test']['recall']:.3f} FPR={r['test']['false_positive_rate']:.3f}")
    (ROOT / "results/ablations.json").write_text(json.dumps(results, indent=1) + "\n", encoding="utf-8")
    L = ["# Ablation study", "", "Each row changes one thing relative to the released configuration. Generated by `python bench/ablations.py`.", "",
         "| variant | test P | test R | test F1 | test FPR | all F1 | all FPR | what changed |", "|---|---|---|---|---|---|---|---|"]
    for r in results:
        t, a = r["test"], r["all"]
        L.append(f"| {r['variant']} | {t['precision']:.3f} | {t['recall']:.3f} | {t['f1']:.3f} | {t['false_positive_rate']:.3f} | {a['f1']:.3f} | {a['false_positive_rate']:.3f} | {r['description']} |")
    (ROOT / "results/ablations.md").write_text("\n".join(L) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
